using System.Windows;
using System.Windows.Controls;
using System.Windows.Input;
using AiSlop.LocalLlm;
using ReaWin.Models;
using ReaWin.Services;

namespace ReaWin;

/// <summary>
/// The AI workspace: a panel over the whole window for one function, showing everything the local model generated for it (the explanation
/// with its names, the alias code beside the decompiled code) and a box for a request about the code. A request is a single round, not a chat
/// (<see cref="AskRunner"/>): it refreshes the explanation, the names and the alias to follow it, and generates the ones that did not exist.
/// Everything shown from the model is tagged as inference; the decompiled code is REA's and is never changed.
/// </summary>
public partial class MainWindow
{
    private ProcedureInfo? _wsProc;
    private bool _wsStatusIsReason;      // the line under the request box currently shows why applying is not possible

    private void SetWsStatus(string text)
    {
        WsStatus.Text = text;
        _wsStatusIsReason = false;
    }
    private bool _wsSyncingScroll;
    private ScrollViewer? _wsOriginalScroll, _wsAliasScroll;

    private bool WorkspaceOpen => WorkspaceOverlay.Visibility == Visibility.Visible;

    private void WorkspaceButton_Click(object sender, RoutedEventArgs e) => OpenWorkspace();

    private void WsClose_Click(object sender, RoutedEventArgs e) => CloseWorkspace();

    private void WsStop_Click(object sender, RoutedEventArgs e) => _aiCts?.Cancel();

    /// <summary>Opens the workspace for the function selected on the Functions tab.</summary>
    private void OpenWorkspace()
    {
        if (FunctionsGrid.SelectedItem is not ProcedureInfo { IsImport: false } proc) return;
        _wsProc = proc;
        WorkspaceOverlay.Visibility = Visibility.Visible;
        EnsureWorkspaceScrollLink();
        RefreshWorkspace();
        WsAskBox.Focus();
    }

    private void CloseWorkspace()
    {
        WorkspaceOverlay.Visibility = Visibility.Collapsed;
        _wsProc = null;
        // what was generated meanwhile is shown on the Functions tab too
        if (FunctionsGrid.SelectedItem is ProcedureInfo selected) { ShowDescriptionFor(selected); UpdateCodeView(selected); }
        RefreshAiUi();
        FunctionsGrid.Focus();
    }

    /// <summary>Esc closes the workspace. Returns true when it did.</summary>
    private bool HandleWorkspaceKey(KeyEventArgs e)
    {
        if (!WorkspaceOpen || e.Key != Key.Escape) return false;
        CloseWorkspace();
        return true;
    }

    // ---- showing what is stored ---------------------------------------------------------------------------

    /// <summary>
    /// Fills the three panes from what is stored for the function: the explanation with its names, the decompiled code, the alias. A missing
    /// piece says how to get it; nothing here is generated by showing it.
    /// </summary>
    private void RefreshWorkspace()
    {
        if (!WorkspaceOpen || _wsProc is not { } proc) return;
        _descriptions.TryGetValue(proc.Address, out var description);
        _aliases.TryGetValue(proc.Address, out var alias);

        WsFunctionText.Text = $"{proc.Name}   @ {proc.Address}";

        WsAliasName.Inlines.Clear();
        WsTitle.Inlines.Clear();
        WsBrief.Inlines.Clear();
        AddLabeled(WsAliasName, "Alias name  ", alias is not null ? alias.Name : null, mono: true);
        AddLabeled(WsTitle, "Readable name  ", description?.Title);
        AddLabeled(WsBrief, "Brief  ", description?.Brief);

        if (description is null)
        {
            WsNote.ToolTip = null;
            WsExplanationBox.Text = "There is no explanation yet. Press Explain on the Functions tab, or type a request below: the explanation, the names and the alias code are written for it.";
            WsNote.Text = "";
        }
        else
        {
            WsExplanationBox.Text = description.Text;
            var note = $"Written by {description.Model} from the decompiled code; it can be wrong. Check it against the code.";
            if (description.Truncated) note += $"\nOnly the first {description.CodeCharsSent:N0} of {description.CodeCharsTotal:N0} characters of the function were shown to the model.";
            if (_aliasFailures.TryGetValue(proc.Address, out var problem)) note += $"\nAlias code: {problem}";
            WsNote.Text = note;
            // the explanation reads as one text; which request shaped it is only a hover away
            WsNote.ToolTip = string.IsNullOrEmpty(description.Request) ? null : $"Shaped by your request: \"{description.Request}\"";
        }

        WsOriginalBox.Text = _decompiled.TryGetValue(proc.Address, out var code)
            ? ForDisplay(code)
            : "// The code of this function is\n// not loaded. Close the workspace\n// and select the function on the\n// Functions tab.";
        WsAliasBox.Text = alias is not null
            ? alias.Code
            : "// No alias code yet.\n// It is written together with\n// the explanation, and again\n// when you apply a request.";

        UpdateWorkspaceState();
    }

    private void AddLabeled(TextBlock block, string label, string? value, bool mono = false)
    {
        var l = new System.Windows.Documents.Run(label);
        l.SetResourceReference(System.Windows.Documents.TextElement.ForegroundProperty, "MutedBrush");
        block.Inlines.Add(l);
        var v = new System.Windows.Documents.Run(string.IsNullOrEmpty(value) ? "not generated yet" : value) { FontWeight = FontWeights.SemiBold };
        if (mono) v.FontFamily = (System.Windows.Media.FontFamily)FindResource("MonoFont");
        v.SetResourceReference(System.Windows.Documents.TextElement.ForegroundProperty, string.IsNullOrEmpty(value) ? "MutedBrush" : "AccentTextBrush");
        block.Inlines.Add(v);
    }

    // ---- the request ---------------------------------------------------------------------------------------

    private void WsAsk_Changed(object sender, TextChangedEventArgs e) => UpdateWorkspaceState();

    private async void WsAsk_KeyDown(object sender, KeyEventArgs e)
    {
        if (e.Key == Key.Enter && Keyboard.Modifiers == ModifierKeys.Control)
        {
            e.Handled = true;
            await RunRequestAsync();
        }
    }

    private async void WsRun_Click(object sender, RoutedEventArgs e) => await RunRequestAsync();

    /// <summary>The run button and the line under the box: what applying would do, or why it cannot be done now.</summary>
    private void UpdateWorkspaceState()
    {
        if (!WorkspaceOpen) return;
        var fault = _llm.Fault;
        var why = _aiBusy ? "The AI is busy; wait for it to finish."
            : !CurrentAi.Enabled ? "AI is off. Turn it on in Settings."
            : fault is not null ? fault
            : AskRunner.Clean(WsAskBox.Text) is null ? "Type a request about the code."
            : null;
        WsRunButton.IsEnabled = why is null;
        WsRunButton.ToolTip = why ?? "Apply the request (Ctrl+Enter): refresh the explanation, the names and the alias code to follow it, written if they do not exist yet. One request, not a chat.";
        WsRunButton.Visibility = _aiBusy ? Visibility.Collapsed : Visibility.Visible;
        WsStopButton.Visibility = _aiBusy ? Visibility.Visible : Visibility.Collapsed;
        // the field is locked while the model works, and takes the cursor back when it is done
        var wasLocked = !WsAskBox.IsEnabled;
        WsAskBox.IsEnabled = !_aiBusy;
        if (wasLocked && !_aiBusy) Dispatcher.BeginInvoke(() => { if (WorkspaceOpen) WsAskBox.Focus(); });
        if (_aiBusy) return;
        // the reason applying is not possible is shown under the box, but never over a message about what a request did
        if (why is not null && (WsStatus.Text.Length == 0 || _wsStatusIsReason)) { WsStatus.Text = why; _wsStatusIsReason = true; }
        else if (why is null && _wsStatusIsReason) { WsStatus.Text = ""; _wsStatusIsReason = false; }
    }

    /// <summary>
    /// Applies the typed request to the function: the same two rounds as an explanation, each given the request. The explanation is kept even if
    /// the alias round fails (the old alias then stays); a request that is not about the code is refused and changes nothing.
    /// </summary>
    private async Task RunRequestAsync()
    {
        if (_aiBusy || _wsProc is not { } proc) return;
        var ask = AskRunner.Clean(WsAskBox.Text);
        if (ask is null) return;

        var llm = _llm;
        var availability = await llm.CheckAsync();
        if (!availability.IsAvailable) { SetWsStatus(availability.Reason ?? "AI is not available."); return; }

        var cts = new CancellationTokenSource();
        _aiCts = cts;
        var ct = cts.Token;
        var generation = _analysisGeneration;
        _aiBusy = true;
        _aiBusyAddress = proc.Address;
        _aiBusyName = proc.Name;
        _aiStage = "";
        SetWsStatus("Starting…");
        RefreshAiUi();
        RefreshChrome();
        UpdateWorkspaceState();
        try
        {
            var code = await CodeForAiAsync(proc);
            if (code is null) { SetWsStatus("No code is available for this function, so there is nothing to ask about."); return; }

            var context = await GatherContextAsync(llm, proc, code, ct);
            _descriptions.TryGetValue(proc.Address, out var previousDescription);
            _aliases.TryGetValue(proc.Address, out var previousAlias);
            var result = await AskRunner.RunAsync(llm, new FunctionToDescribe(proc.Name, proc.Address, code), context, ask,
                previousDescription, previousAlias, CalleeAliasNames(proc), CurrentAi.ContextSize, new Progress<string>(SetAiStage), ct);

            if (generation != _analysisGeneration) return;
            _descriptions[proc.Address] = result.Description;
            if (result.Alias is { } alias) { _aliases[proc.Address] = alias; _aliasFailures.Remove(proc.Address); }
            else if (result.AliasProblem is { } problem) _aliasFailures[proc.Address] = problem;   // the old alias, if any, stays: it is still the same code
            _dirty = true;
            await StoreProjectAsync();   // a request can take a minute: keep what it produced at once

            WsAskBox.Clear();   // answered: the request is shown with the explanation it produced ("For your request: …")
            SetWsStatus(result.Alias is not null
                ? "Done: the explanation, the names and the alias code now follow your request."
                : $"The explanation and the names follow your request. No new alias code: {result.AliasProblem}");
        }
        catch (OperationCanceledException) { SetWsStatus("Stopped."); }
        catch (RequestRefusedException ex)
        {
            WsAskBox.Clear();   // the model answered, with a refusal
            SetWsStatus($"Not handled: {ex.Message} Ask something about this code. Nothing was changed.");
        }
        catch (LlmContextExceededException ex) { SetWsStatus(ex.Message); }
        catch (LlmUnavailableException ex) { Log($"AI failed:\n{ex.Message}"); SetWsStatus(ex.Message); }
        catch (DescriptionException ex) { SetWsStatus(ex.Message); }
        finally
        {
            _aiBusy = false;
            _aiBusyAddress = null;
            cts.Dispose();
            _aiCts = null;
            AliasesChanged();       // the list, the graph, the code view and (through it) the workspace
            RefreshAiUi();
            RefreshChrome();
        }
    }

    // ---- scrolling the two code panes together -----------------------------------------------------------------

    /// <summary>
    /// Links the vertical scrolling of the decompiled code and the alias. The alias has comments, so its lines do not match one to one; the two
    /// keep the same relative position, which keeps the beginnings and the ends together.
    /// </summary>
    private void EnsureWorkspaceScrollLink()
    {
        if (_wsOriginalScroll is not null) return;
        WsOriginalBox.ApplyTemplate();
        WsAliasBox.ApplyTemplate();
        _wsOriginalScroll = WsOriginalBox.Template.FindName("PART_ContentHost", WsOriginalBox) as ScrollViewer;
        _wsAliasScroll = WsAliasBox.Template.FindName("PART_ContentHost", WsAliasBox) as ScrollViewer;
        if (_wsOriginalScroll is not null) _wsOriginalScroll.ScrollChanged += (_, e) => LinkScroll(_wsOriginalScroll, _wsAliasScroll, e);
        if (_wsAliasScroll is not null) _wsAliasScroll.ScrollChanged += (_, e) => LinkScroll(_wsAliasScroll, _wsOriginalScroll, e);
    }

    private void LinkScroll(ScrollViewer from, ScrollViewer? to, ScrollChangedEventArgs e)
    {
        if (to is null || _wsSyncingScroll || WsLinkScroll.IsChecked != true || e.VerticalChange == 0) return;
        var fromRange = from.ExtentHeight - from.ViewportHeight;
        var toRange = to.ExtentHeight - to.ViewportHeight;
        if (fromRange <= 0 || toRange <= 0) return;
        _wsSyncingScroll = true;
        try { to.ScrollToVerticalOffset(from.VerticalOffset / fromRange * toRange); }
        finally { _wsSyncingScroll = false; }
    }
}
